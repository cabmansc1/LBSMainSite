/* ---------- reads ---------- */

export type EventQuery = {
  category?: EventCategory;
  placeSlug?: string;
  businessId?: number;
  limit?: number;
  offset?: number;
  /** Include events that have already happened. */
  includePast?: boolean;
};

/**
 * Upcoming, published, soonest first.
 *
 * "Upcoming" is judged against the end where there is one, so a
 * three-day festival stays on the calendar on its second day rather
 * than vanishing the morning after it opened.
 */
export async function publishedEvents(q: EventQuery = {}): Promise<LocalEvent[]> {
  const limit = Math.min(Math.max(q.limit ?? 24, 1), 100);
  const offset = Math.max(q.offset ?? 0, 0);
  try {
    const { db } = await import("@/lib/db");
    const where = [sql`e.status = 'published'`];
    if (!q.includePast) {
      where.push(sql`COALESCE(e.ends_at, e.starts_at) >= NOW()`);
    }
    if (q.category) where.push(sql`e.category = ${q.category}`);
    if (q.placeSlug) where.push(sql`e.place_slug = ${q.placeSlug}`);
    if (q.businessId) where.push(sql`e.business_id = ${q.businessId}`);
    const rows = (await db.execute(
      sql`${SELECT} WHERE ${sql.join(where, sql` AND `)}
           ORDER BY e.starts_at ${q.includePast ? sql`DESC` : sql`ASC`}
           LIMIT ${limit} OFFSET ${offset}`,
    )) as unknown as [Row[]];
    return (rows[0] ?? []).map(toEvent);
  } catch (e) {
    console.error("[events] list failed:", e);
    return [];
  }
}

export async function countPublishedEvents(q: EventQuery = {}): Promise<number> {
  try {
    const { db } = await import("@/lib/db");
    const where = [sql`status = 'published'`];
    if (!q.includePast) {
      where.push(sql`COALESCE(ends_at, starts_at) >= NOW()`);
    }
    if (q.category) where.push(sql`category = ${q.category}`);
    if (q.placeSlug) where.push(sql`place_slug = ${q.placeSlug}`);
    const rows = (await db.execute(
      sql`SELECT COUNT(*) AS n FROM lbs_events WHERE ${sql.join(where, sql` AND `)}`,
    )) as unknown as [{ n: number | string }[]];
    return Number(rows[0]?.[0]?.n ?? 0);
  } catch {
    return 0;
  }
}

export async function getPublishedEvent(
  slug: string,
): Promise<LocalEvent | undefined> {
  try {
    const { db } = await import("@/lib/db");
    const rows = (await db.execute(
      sql`${SELECT} WHERE e.slug = ${slug} AND e.status = 'published' LIMIT 1`,
    )) as unknown as [Row[]];
    const r = rows[0]?.[0];
    return r ? toEvent(r) : undefined;
  } catch (e) {
    console.error("[events] read failed:", e);
    return undefined;
  }
}

