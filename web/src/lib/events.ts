const CATEGORIES = new Set<string>([
  "festival",
  "market",
  "concert",
  "family",
  "food",
  "grand_opening",
  "charity",
  "community",
]);
const STATUSES = new Set<string>([
  "pending",
  "published",
  "rejected",
  "archived",
]);

let ready = false;

/**
 * Created on write, including the public submission.
 *
 * That is the one public path allowed to run DDL here, for the same
 * reason the unsubscribe table is: the alternative is that the very
 * first person to submit an event gets an error, and a submission form
 * that fails on its first use never gets a second.
 */
async function ensureTable() {
  if (ready) return;
  const { db } = await import("@/lib/db");
  await db.execute(
    sql`CREATE TABLE IF NOT EXISTS lbs_events (
      id INT AUTO_INCREMENT PRIMARY KEY,
      slug VARCHAR(180) NOT NULL UNIQUE,
      title VARCHAR(300) NOT NULL,
      summary TEXT NULL,
      body_html MEDIUMTEXT NULL,
      hero_media_id INT NULL,
      starts_at DATETIME NOT NULL,
      ends_at DATETIME NULL,
      all_day TINYINT NOT NULL DEFAULT 0,
      venue_name VARCHAR(200) NULL,
      address VARCHAR(300) NULL,
      place_slug VARCHAR(80) NULL,
      business_id INT NULL,
      category VARCHAR(24) NOT NULL DEFAULT 'community',
      url VARCHAR(500) NULL,
      ticket_url VARCHAR(500) NULL,
      price_text VARCHAR(120) NULL,
      status VARCHAR(16) NOT NULL DEFAULT 'pending',
      featured TINYINT NOT NULL DEFAULT 0,
      source VARCHAR(16) NOT NULL DEFAULT 'staff',
      submitted_email VARCHAR(191) NULL,
      series_id INT NULL,
      external_source VARCHAR(40) NULL,
      external_id VARCHAR(191) NULL,
      source_url VARCHAR(500) NULL,
      created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
      KEY when_idx (status, starts_at),
      KEY place_idx (place_slug),
      KEY series_idx (series_id),
      UNIQUE KEY external_ref (external_source, external_id)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`,
  );

  /**
   * Room for a feed, before there is one.
   *
   * Nothing writes these yet. They exist because the expensive half of
   * ingesting somebody else's calendar is not the fetching, it is
   * knowing whether you already have the row — and that has to be
   * decided against an identifier the other side controls, not against
   * a title, which they will edit. Retrofitting the key after a few
   * thousand rows have landed means reconciling duplicates by hand.
   *
   * The provider is stored beside the identifier because two feeds will
   * eventually both hand over an id of "1042". `source_url` is where we
   * got it from, which is a different thing from `url`: that one is the
   * event's own page, and is what a reader is sent to.
   *
   * MySQL lets a unique index hold any number of rows whose columns are
   * both NULL, so everything typed in by hand is unaffected.
   */
  for (const stmt of [
    sql`ALTER TABLE lbs_events
        ADD COLUMN external_source VARCHAR(40) NULL,
        ADD COLUMN external_id VARCHAR(191) NULL,
        ADD COLUMN source_url VARCHAR(500) NULL`,
    sql`ALTER TABLE lbs_events
        ADD UNIQUE KEY external_ref (external_source, external_id)`,
  ]) {
    // Tolerated rather than checked, as elsewhere: the only reason
    // either fails is that it has already been applied, and the
    // submission form must not start erroring over a column it has.
    try {
      await db.execute(stmt);
    } catch {
      /* already there */
    }
  }
  ready = true;
}

type Row = {
  id: number;
  slug: string;
  title: string;
  summary: string | null;
  body_html: string | null;
  hero_media_id: number | null;
  starts_at: unknown;
  ends_at: unknown;
  all_day: number | null;
  venue_name: string | null;
  address: string | null;
  place_slug: string | null;
  business_id: number | null;
  business_name?: string | null;
  business_slug?: string | null;
  category: string;
  url: string | null;
  ticket_url: string | null;
  price_text: string | null;
  status: string;
  featured: number | null;
  source: string;
  submitted_email: string | null;
  series_id: number | null;
  // Optional because the public reads never run the ALTER above, so a
  // database that has not had a write since this shipped answers
  // SELECT e.* without them.
  external_source?: string | null;
  external_id?: string | null;
  source_url?: string | null;
};

const asDate = (d: unknown) => {
  const dt = d instanceof Date ? d : new Date(String(d ?? ""));
  return isNaN(dt.getTime()) ? undefined : dt;
};

const iso = (d: unknown) => asDate(d)?.toISOString() ?? "";

const toEvent = (r: Row): LocalEvent => {
  const start = asDate(r.starts_at);
  const end = asDate(r.ends_at);
  const allDay = Number(r.all_day) === 1;
  // Compared by calendar day rather than by elapsed hours, so a thing
  // running 8pm to 1am is one night out and not a two-day event.
  const multiDay =
    !!start && !!end && start.toDateString() !== end.toDateString();
  return {
    id: Number(r.id),
    slug: String(r.slug),
    title: String(r.title ?? ""),
    summary: r.summary ?? "",
    bodyHtml: r.body_html ?? "",
    heroMediaId: r.hero_media_id ?? null,
    startsAt: iso(r.starts_at),
    endsAt: iso(r.ends_at),
    allDay,
    venueName: r.venue_name ?? "",
    address: r.address ?? "",
    placeSlug: r.place_slug ?? "",
    businessId: r.business_id ?? null,
    businessName: r.business_name ?? undefined,
    businessSlug: r.business_slug ?? undefined,
    category: (CATEGORIES.has(r.category)
      ? r.category
      : "community") as EventCategory,
    url: r.url ?? "",
    ticketUrl: r.ticket_url ?? "",
    priceText: r.price_text ?? "",
    status: (STATUSES.has(r.status) ? r.status : "pending") as EventStatus,
    featured: Number(r.featured) === 1,
    source: (r.source === "submitted" || r.source === "imported"
      ? r.source
      : "staff") as EventSource,
    submittedEmail: r.submitted_email ?? "",
    seriesId: r.series_id ?? null,
    externalSource: r.external_source ?? "",
    externalId: r.external_id ?? "",
    sourceUrl: r.source_url ?? "",
    dayLabel: start?.toLocaleDateString("en-US", {
      weekday: "long",
      month: "long",
      day: "numeric",
    }),
    monthLabel: start?.toLocaleDateString("en-US", { month: "short" }),
    dayOfMonth: start ? String(start.getDate()) : undefined,
    // An all-day thing has no useful clock time, and printing 12:00 AM
    // beside it reads as a mistake rather than as "all day".
    timeLabel: allDay
      ? "All day"
      : start?.toLocaleTimeString("en-US", {
          hour: "numeric",
          minute: "2-digit",
        }),
    multiDay,
    endDayLabel: end?.toLocaleDateString("en-US", {
      weekday: "long",
      month: "long",
      day: "numeric",
    }),
    endTimeLabel: allDay
      ? undefined
      : end?.toLocaleTimeString("en-US", {
          hour: "numeric",
          minute: "2-digit",
        }),
  };
};

