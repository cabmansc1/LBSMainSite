/** A ceiling, so a mistyped date cannot fill the table. */
const MAX_REPEATS = 52;

/**
 * Copies an event forward, one real row a week.
 *
 * This is the whole of the recurrence support, on purpose. Every copy
 * is an ordinary event that can be edited, moved or cancelled on its
 * own, and they share a series id only so they can be found together.
 * Nothing here has to understand "every third Saturday except in
 * December", because nothing here has to: that is just a week somebody
 * deletes.
 */
export async function repeatWeekly(
  id: number,
  weeks: number,
): Promise<{ ok: true; made: number } | { ok: false; error: string }> {
  const n = Math.min(Math.max(Math.round(weeks), 1), MAX_REPEATS);
  const source = await getEvent(id);
  if (!source) return { ok: false, error: "That event is not here any more." };
  const start = asDate(source.startsAt);
  if (!start) return { ok: false, error: "That event has no start date." };

  try {
    await ensureTable();
    const { db } = await import("@/lib/db");
    // The first of a series adopts its own id, so the original is part
    // of the series rather than an odd one out beside it.
    const seriesId = source.seriesId ?? source.id;
    if (source.seriesId === null) {
      await db.execute(
        sql`UPDATE lbs_events SET series_id = ${seriesId} WHERE id = ${id}`,
      );
    }

    const end = asDate(source.endsAt);
    const span = end ? end.getTime() - start.getTime() : null;
    let made = 0;
    for (let w = 1; w <= n; w += 1) {
      const nextStart = new Date(start.getTime());
      nextStart.setDate(nextStart.getDate() + 7 * w);
      const nextEnd = span === null ? null : new Date(nextStart.getTime() + span);
      const slug = await freeSlug(
        slugFor(source.title, nextStart.toISOString()),
        null,
      );
      await db.execute(
        sql`INSERT INTO lbs_events
              (slug, title, summary, body_html, hero_media_id, starts_at,
               ends_at, all_day, venue_name, address, place_slug, business_id,
               category, url, ticket_url, price_text, status, featured,
               source, submitted_email, series_id)
            VALUES (${slug}, ${source.title}, ${source.summary},
                    ${source.bodyHtml}, ${source.heroMediaId}, ${nextStart},
                    ${nextEnd}, ${source.allDay ? 1 : 0}, ${source.venueName},
                    ${source.address}, ${source.placeSlug || null},
                    ${source.businessId}, ${source.category}, ${source.url},
                    ${source.ticketUrl}, ${source.priceText},
                    ${source.status}, 0, ${source.source},
                    ${source.submittedEmail}, ${seriesId})`,
      );
      made += 1;
    }
    return { ok: true, made };
  } catch (e) {
    console.error("[events] repeat failed:", e);
    return { ok: false, error: "Those did not save." };
  }
}

