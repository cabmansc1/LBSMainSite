export type SubmissionInput = {
  title: string;
  startsAt: string;
  endsAt: string;
  allDay: boolean;
  venueName: string;
  address: string;
  placeSlug: string;
  category: EventCategory;
  summary: string;
  url: string;
  email: string;
  priceText: string;
  /**
   * A picture, already through the media library.
   *
   * Nothing it is attached to is public until somebody approves it, so
   * an unwanted image is a row in a queue rather than something on the
   * site. The bytes have been re-encoded by then, which is most of why
   * accepting one from a stranger is reasonable at all.
   */
  heroMediaId: number | null;
};

/**
 * Takes an event from the public form.
 *
 * Always pending, never published, whatever the form says. The status
 * is not read from the request at all rather than being validated out
 * of it, because a field that is never accepted cannot be got past by
 * anybody clever with a console.
 */
export async function submitEvent(
  input: SubmissionInput,
): Promise<EventResult> {
  return saveEvent(null, {
    title: input.title,
    summary: input.summary,
    // No body from the public form. Prose from a stranger rendered on
    // our pages is a different question from a line of plain text, and
    // it is not one a submission box needs to open.
    bodyHtml: "",
    heroMediaId: input.heroMediaId,
    startsAt: input.startsAt,
    endsAt: input.endsAt,
    allDay: input.allDay,
    venueName: input.venueName,
    address: input.address,
    placeSlug: input.placeSlug,
    businessId: null,
    category: input.category,
    url: input.url,
    ticketUrl: "",
    priceText: input.priceText,
    status: "pending",
    featured: false,
    source: "submitted",
    submittedEmail: input.email,
  });
}
