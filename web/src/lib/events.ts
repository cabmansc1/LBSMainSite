export type EventResult =
  | { ok: true; id: number; slug: string }
  | { ok: false; error: string };

async function freeSlug(base: string, exceptId: number | null): Promise<string> {
  const { db } = await import("@/lib/db");
  const root = base || "event";
  for (let n = 0; n < 60; n += 1) {
    const candidate = n === 0 ? root : `${root}-${n + 1}`;
    const rows = (await db.execute(
      sql`SELECT id FROM lbs_events WHERE slug = ${candidate} LIMIT 1`,
    )) as unknown as [{ id: number }[]];
    const found = rows[0]?.[0];
    if (!found || (exceptId !== null && Number(found.id) === exceptId)) {
      return candidate;
    }
  }
  return `${root}-${Date.now()}`;
}

/**
 * A slug that carries the date.
 *
 * A weekly market would otherwise produce "summerville-farmers-market",
 * then "-2", then "-3", and nobody could tell which week a link pointed
 * at. The date makes every instance of a series readable on its own.
 */
const slugFor = (title: string, startsAt: string) => {
  const d = asDate(startsAt);
  const stamp = d
    ? `-${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(
        d.getDate(),
      ).padStart(2, "0")}`
    : "";
  return `${slugifyEvent(title)}${stamp}`;
};

export async function saveEvent(
  id: number | null,
  patch: EventPatch,
): Promise<EventResult> {
  const title = patch.title.trim();
  if (title.length < 3) return { ok: false, error: "Give the event a name." };
  const start = asDate(patch.startsAt);
  if (!start) return { ok: false, error: "When does it start?" };
  const end = asDate(patch.endsAt);
  if (end && end < start) {
    return { ok: false, error: "It cannot end before it starts." };
  }

  try {
    await ensureTable();
    const { db } = await import("@/lib/db");
    const body = cleanStoryHtml(patch.bodyHtml ?? "");
    const category = CATEGORIES.has(patch.category)
      ? patch.category
      : "community";
    const status = STATUSES.has(patch.status) ? patch.status : "pending";

    if (id) {
      // The slug stops following the name once it is live, the same rule
      // stories follow: a published event's address may be in a
      // newsletter already.
      const cur = (await db.execute(
        sql`SELECT slug, status FROM lbs_events WHERE id = ${id} LIMIT 1`,
      )) as unknown as [{ slug: string; status: string }[]];
      const row = cur[0]?.[0];
      if (!row) return { ok: false, error: "That event is not here any more." };
      const finalSlug =
        row.status === "published"
          ? String(row.slug)
          : await freeSlug(slugFor(title, patch.startsAt), id);

      await db.execute(
        sql`UPDATE lbs_events
               SET slug = ${finalSlug}, title = ${title},
                   summary = ${patch.summary ?? ""}, body_html = ${body},
                   hero_media_id = ${patch.heroMediaId},
                   starts_at = ${start}, ends_at = ${end ?? null},
                   all_day = ${patch.allDay ? 1 : 0},
                   venue_name = ${patch.venueName ?? ""},
                   address = ${patch.address ?? ""},
                   place_slug = ${patch.placeSlug || null},
                   business_id = ${patch.businessId},
                   category = ${category}, url = ${patch.url ?? ""},
                   ticket_url = ${patch.ticketUrl ?? ""},
                   price_text = ${patch.priceText ?? ""},
                   status = ${status}, featured = ${patch.featured ? 1 : 0}
             WHERE id = ${id}`,
      );
      return { ok: true, id, slug: finalSlug };
    }

    const slug = await freeSlug(slugFor(title, patch.startsAt), null);
    await db.execute(
      sql`INSERT INTO lbs_events
            (slug, title, summary, body_html, hero_media_id, starts_at,
             ends_at, all_day, venue_name, address, place_slug, business_id,
             category, url, ticket_url, price_text, status, featured,
             source, submitted_email)
          VALUES (${slug}, ${title}, ${patch.summary ?? ""}, ${body},
                  ${patch.heroMediaId}, ${start}, ${end ?? null},
                  ${patch.allDay ? 1 : 0}, ${patch.venueName ?? ""},
                  ${patch.address ?? ""}, ${patch.placeSlug || null},
                  ${patch.businessId}, ${category}, ${patch.url ?? ""},
                  ${patch.ticketUrl ?? ""}, ${patch.priceText ?? ""},
                  ${status}, ${patch.featured ? 1 : 0},
                  ${patch.source ?? "staff"}, ${patch.submittedEmail ?? ""})`,
    );
    const back = (await db.execute(
      sql`SELECT id FROM lbs_events WHERE slug = ${slug} LIMIT 1`,
    )) as unknown as [{ id: number }[]];
    const newId = Number(back[0]?.[0]?.id ?? 0);
    if (!newId) return { ok: false, error: "That saved but could not be read back." };
    return { ok: true, id: newId, slug };
  } catch (e) {
    console.error("[events] save failed:", e);
    return { ok: false, error: "That did not save." };
  }
}

export async function setEventStatus(
  id: number,
  status: EventStatus,
): Promise<{ ok: true } | { ok: false; error: string }> {
  if (!STATUSES.has(status)) return { ok: false, error: "Unknown status." };
  try {
    await ensureTable();
    const { db } = await import("@/lib/db");
    await db.execute(
      sql`UPDATE lbs_events SET status = ${status} WHERE id = ${id}`,
    );
    return { ok: true };
  } catch (e) {
    console.error("[events] status failed:", e);
    return { ok: false, error: "That did not save." };
  }
}

