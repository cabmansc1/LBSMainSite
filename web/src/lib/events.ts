/**
 * What's Happening.
 *
 * The second reason for a resident to come back, and the half of the
 * roadmap that gives the directory something to sit beside. An event
 * belongs to a place and often to a business, which is what puts it on
 * that business's listing without anybody linking it twice.
 *
 * Two decisions worth stating. There are no recurrence rules: a weekly
 * market is a real row per week sharing a series id, generated by a
 * button, so moving or cancelling one week is an ordinary edit rather
 * than an exception buried inside a rule. And anybody can submit one,
 * because a calendar only Andrew can fill is a weekly chore with no end
 * date, and that is how local event calendars quietly die around month
 * four.
 */

